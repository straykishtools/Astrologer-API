class HafezInterpreter:
    """تعبیر تفأل حافظ بر اساس مضمونِ غزل"""

    def __init__(self, ghazals_dir: Optional[str] = None):
        # پوشه‌ی غزل‌ها برای استخراجِ متن
        if ghazals_dir is None:
            base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
            ghazals_dir = os.path.join(base, "data", "hafez_ghazals")
        self.ghazals_dir = ghazals_dir

    def _load_ghazal_text(self, ghazal_number: int) -> str:
        """متنِ کاملِ غزل برایِ تحلیلِ مضمون"""
        path = os.path.join(self.ghazals_dir, f"sh{ghazal_number}.json")
        if not os.path.exists(path):
            return ""
        try:
            with open(path, encoding="utf-8") as f:
                data = json.load(f)
            # جمعِ همه‌ی متن‌ها
            parts = []
            def walk(o):
                if isinstance(o, dict):
                    for v in o.values():
                        walk(v)
                elif isinstance(o, list):
                    for v in o:
                        walk(v)
                elif isinstance(o, str):
                    parts.append(o)
            walk(data)
            return " ".join(parts)
        except Exception:
            return ""

    def interpret(self, ghazal_number: int, question: Optional[str] = None) -> Dict:
        """تعبیر فال بر اساس مضمونِ غزل + سؤالِ کاربر"""
        text = self._load_ghazal_text(ghazal_number).lower()

        # امتیازدهیِ مضامین
        best_theme = None
        best_score = 0
        for theme in THEMES:
            score = 0
            for kw in theme["keywords"]:
                if kw.lower() in text:
                    score += text.count(kw.lower())
            if score > best_score:
                best_score = score
                best_theme = theme

        # اگر هیچ مضمونی مطابقت نکرد (متنِ خالی یا کلماتِ ناشناخته)
        if not best_theme or best_score == 0:
            best_theme = {
                "id": "general",
                "title": "تفألِ عام 🌿",
                "omen": "این غزل از آن دسته‌های است که هر کس به اقتضای حالِ دلِ خودش معنی می‌برد — و شاید همین زیباییِ حافظ باشد. پیامِ کلی‌اش: راهِ تو زیرِ پایت است؛ با ادب ادامه بده و از هر رخداد، درسی بردار. حافظ با تو یار است.",
                "advice": "بعد از چند روز دوباره فال بگیر؛ یا سؤالِ خود را دقیق‌تر بنویس تا پیامِ روشن‌تری بیاید.",
                "tone": "میانه ⚖️",
            }

        result = {
            "theme_title": best_theme["title"],
            "omen": best_theme["omen"],
            "advice": best_theme["advice"],
            "tone": best_theme["tone"],
        }

        # اگر سؤالِ کاربر درباره‌ی عشق/کار/پول باشد، پیام را دقیق‌تر کن
        if question:
            q = question.lower()
            q_add = []
            if any(k in q for k in ["عشق", "ازدواج", "رابطه", "خواستگار", "دوست", "دلبر"]):
                q_add.append("با توجه به سؤالِ شما (عشق و رابطه): این فال به نفعِ نزدیکی و گفت‌وگوی صادقانه است — قدمِ اولِ مهر بگذار.")
            if any(k in q for k in ["کار", "شغل", "استخدام", "پروژه"]):
                q_add.append("با توجه به سؤالِ شما (کار): تلاشت دیده می‌شود؛ ادامه بده و در جلسه‌ی مهمِ پیشِ رو آماده باش.")
            if any(k in q for k in ["پول", "مال", "قرض", "بدهی", "سرمایه"]):
                q_add.append("با توجه به سؤالِ شما (مالی): گشایشِ مالی نزدیک است اما با برنامه — از بدهکارِ جدیدِ پرهیز کن و دَینِ خودت را بده.")
            if any(k in q for k in ["سلامت", "بیمار", "درمان"]):
                q_add.append("با توجه به سؤالِ شما (سلامت): روندِ بهبود در جریان است؛ صبر و پیگیریِ درمان، نتیجه می‌دهد.")
            if any(k in q for k in ["سفر", "مهاجرت", "رفتن"]):
                q_add.append("با توجه به سؤالِ شما (سفر): راهِ باز است؛ مقدمات را با مشورتِ آگاهان ببند.")
            if q_add:
                result["question_specific"] = " ".join(q_add)

        return result
