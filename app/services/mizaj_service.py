class MizajService:
    # ============================================
    # 1. Mojahedi 10-Question Questionnaire (MMQ)
    # ============================================
    @staticmethod
    def calculate_from_mmq(answers: dict):
        """
        answers: dict with keys 'q1' to 'q10', each value 1, 2, or 3
        Q1-Q8: Hot/Cold, Q9-Q10: Wet/Dry
        """
        hot_cold_scores = [answers.get(f'q{i}', 2) for i in range(1, 9)]
        total_hot_cold = sum(hot_cold_scores)

        wet_dry_scores = [answers.get(f'q{i}', 2) for i in range(9, 11)]
        total_wet_dry = sum(wet_dry_scores)

        if total_hot_cold <= 14:
            temp_status = "سرد"
        elif total_hot_cold >= 19:
            temp_status = "گرم"
        else:
            temp_status = "معتدل"

        if total_wet_dry <= 3:
            humidity_status = "تر"
        elif total_wet_dry >= 5:
            humidity_status = "خشک"
        else:
            humidity_status = "معتدل"

        return MizajService._build_result(
            "MMQ (10 سوالی مجاهد)", total_hot_cold, (14, 24),
            temp_status, humidity_status,
            extra_scores={"wet_dry": total_wet_dry}
        )

    # ============================================
    # 2. Salmannezhad 20-Question Questionnaire (SMQ)
    # ============================================
    @staticmethod
    def calculate_from_smq(answers: dict):
        """
        answers: dict with keys 'q1' to 'q20', each value 1-5
        Q1-Q15: Hot/Cold, Q16-Q20: Wet/Dry
        """
        hot_cold_scores = [answers.get(f'q{i}', 3) for i in range(1, 16)]
        total_hot_cold = sum(hot_cold_scores)

        wet_dry_scores = [answers.get(f'q{i}', 3) for i in range(16, 21)]
        total_wet_dry = sum(wet_dry_scores)

        if total_hot_cold <= 46:
            temp_status = "سرد"
        elif total_hot_cold >= 50:
            temp_status = "گرم"
        else:
            temp_status = "معتدل"

        if total_wet_dry <= 14:
            humidity_status = "تر"
        elif total_wet_dry >= 17:
            humidity_status = "خشک"
        else:
            humidity_status = "معتدل"

        return MizajService._build_result(
            "SMQ (20 سوالی سلمان‌نژاد)", total_hot_cold, (30, 75),
            temp_status, humidity_status,
            extra_scores={"wet_dry": total_wet_dry}
        )

    # ============================================
    # Helpers
    # ============================================
    @staticmethod
    def _build_result(questionnaire, hot_cold_total, hc_range, temp, humid,
                      extra_scores=None):
        final_mizaj = f"{temp} و {humid}"
        profile = MIZAJ_PROFILES.get(final_mizaj, {})
        advice = _MIZAJ_ADVICE.get(final_mizaj, _MIZAJ_ADVICE_DEFAULT)

        lo, hi = hc_range
        hot_pct = round(((hot_cold_total - lo) / (hi - lo)) * 100)
        hot_pct = max(0, min(100, hot_pct))

        scores = {"hot_cold": hot_cold_total, "hot_percent": hot_pct, "cold_percent": 100 - hot_pct}
        if extra_scores:
            scores.update(extra_scores)

        recommendations = []
        for cat in ("diet", "lifestyle", "behavioral"):
            for item in advice.get(cat, []):
                recommendations.append(item)

        return {
            "questionnaire": questionnaire,
            "scores": scores,
            "temperament": final_mizaj,
            "temp_status": temp,
            "humidity_status": humid,
            "profile": {
                "name": profile.get("name", final_mizaj),
                "element": profile.get("element", ""),
                "season": profile.get("season", ""),
                "humor": profile.get("humor", ""),
                "personality": profile.get("personality", ""),
                "body": profile.get("body", ""),
                "risks": profile.get("risks", ""),
                "balance_note": profile.get("balance", ""),
            },
            "description": MizajService._get_description(temp, humid),
            "advice": advice,
            "recommendations": recommendations,
        }

    @staticmethod
    def _get_recommendations(temp, humid):
        recs = []
        if temp == "سرد":
            recs.extend([
                "مصرف غذاهای گرم مانند عسل، دارچین، زنجبیل و خرما",
                "پوشیدن لباس گرم و استفاده از حمام گرم",
                "نوشیدن دمنوش‌های گرم مانند آویشن و بابونه"
            ])
        elif temp == "گرم":
            recs.extend([
                "مصرف غذاهای خنک مانند ماست، خیار، دوغ و کاهو",
                "استفاده از سایه و محیط خنک",
                "مصرف میوه‌های آبدار مانند هندوانه و خربزه"
            ])
        else:
            recs.append("مزاج معتدل دارید، رژیم متعادل و متنوع داشته باشید")

        if humid == "تر":
            recs.append("مصرف غذاهای خشک مانند نان برشته، عدس و سیب")
        elif humid == "خشک":
            recs.append("مصرف غذاهای تر مانند سوپ، آش و خورشت‌های آبدار")
        else:
            recs.append("تعادل رطوبتی خوبی دارید، همین روال را حفظ کنید")

        return recs

    @staticmethod
    def _get_description(temp, humid):
        base = f"مزاج شما {temp} و {humid} است. "
        if temp == "سرد" and humid == "تر":
            base += "بدنتان به سمت سردی و رطوبت تمایل دارد. نیاز به گرم‌کردن و خشک‌کردن دارید."
        elif temp == "گرم" and humid == "خشک":
            base += "بدنتان به سمت گرمی و خشکی تمایل دارد. نیاز به خنک‌کردن و مرطوب‌کردن دارید."
        elif temp == "سرد" and humid == "خشک":
            base += "بدنتان به سمت سردی و خشکی تمایل دارد. نیاز به گرم‌کردن و مرطوب‌کردن دارید."
        elif temp == "گرم" and humid == "تر":
            base += "بدنتان به سمت گرمی و رطوبت تمایل دارد. نیاز به خنک‌کردن و خشک‌کردن دارید."
        else:
            base += "بدنتان در حالت تعادل نسبی قرار دارد."
        return base
