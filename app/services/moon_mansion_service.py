_MANSION_SPAN = 360.0 / 28.0  # ~12.857


class MoonMansionService:
    """منزل قمر برای لحظه اکنون"""

    @staticmethod
    def _moon_longitude(date: datetime) -> float:
        """طول جئوپتریک دقیق ماه (درجه) — فرمول‌های نجومی معتبر (±0.3°)

        ترکیب: طول میانگین + انحراف مرکزی + معادلات عمده (evection/variation).
        """
        # قرن‌های ژولینی از J2000.0
        jd = date.timestamp() / 86400.0 + 2440587.5
        T = (jd - 2451545.0) / 36525.0

        # Longitudes منظم (Meeus ch.47 — ساده‌شده با جمله‌های عمده)
        Lp = (218.3164477 + 481267.88123421 * T
              - 0.0015786 * T * T + T * T * T / 538841) % 360.0
        D = (297.8501921 + 445267.1114034 * T
             - 0.0018819 * T * T + T * T * T / 545868) % 360.0
        M = (357.5291092 + 35999.0502909 * T
             - 0.0001536 * T * T) % 360.0
        Mp = (134.9633964 + 477198.8675055 * T
              + 0.0087414 * T * T + T * T * T / 69699) % 360.0
        F = (93.2720950 + 483202.0175233 * T
             - 0.0036539 * T * T - T * T * T / 3526000) % 360.0

        def sin(d): return math.sin(math.radians(d))
        def cos(d): return math.cos(math.radians(d))

        # جمله‌های عمده طول (کافی برای دقت ~0.2 درجه)
        lon = (Lp
            + 6.288774 * sin(Mp)
            + 1.274027 * sin(2 * D - Mp)
            + 0.658314 * sin(2 * D)
            + 0.213618 * sin(2 * Mp)
            - 0.185116 * sin(M)
            - 0.114332 * sin(2 * F)
            + 0.058793 * sin(2 * D - 2 * Mp)
            + 0.057066 * sin(2 * D - M - Mp)
            + 0.053322 * sin(2 * D + Mp)
            + 0.045758 * sin(2 * D - M)
            - 0.040923 * sin(M - Mp)
            - 0.034720 * sin(D)
            - 0.030383 * sin(M + Mp)
            + 0.015327 * sin(2 * D - 2 * F)
            - 0.012528 * sin(Mp + 2 * F)
            + 0.010980 * sin(Mp - 2 * F)
            + 0.010675 * sin(4 * D - Mp)
            + 0.010034 * sin(3 * Mp)
            + 0.008548 * sin(4 * D - 2 * Mp)
            - 0.007888 * sin(2 * D + M - Mp)
            - 0.006766 * sin(2 * D + M)
            - 0.005163 * sin(D - Mp)
            + 0.004987 * sin(D + M)
            + 0.004036 * sin(2 * D - M + Mp)
            + 0.003994 * sin(2 * D + 2 * Mp)
            + 0.003861 * sin(4 * D)
            + 0.003665 * sin(2 * D - 3 * Mp)
            - 0.002689 * sin(M - 2 * Mp)
            - 0.002602 * sin(2 * D - Mp + 2 * F)
            + 0.002390 * sin(2 * D - M - 2 * Mp)
            - 0.002348 * sin(D + Mp)
            + 0.002236 * sin(2 * D - 2 * M)
            - 0.002120 * sin(M + 2 * Mp)
            + 0.002069 * sin(2 * M)
            - 0.002048 * sin(2 * D - M - 2 * Mp + 2 * F)
            - 0.001773 * sin(2 * D + Mp - 2 * F)
            - 0.001595 * sin(2 * D + 2 * F)
            + 0.001215 * sin(4 * D - M - Mp)
            - 0.001110 * sin(2 * Mp + 2 * F)
            - 0.000892 * sin(3 * D - Mp)
            - 0.000810 * sin(2 * D + M + Mp)
            + 0.000759 * sin(4 * D - M - 2 * Mp)
            - 0.000713 * sin(2 * M - Mp)
            - 0.000700 * sin(2 * D + 2 * M - 2 * Mp)
            + 0.000691 * sin(2 * D + M - 2 * Mp + 2 * F)
            + 0.000596 * sin(2 * D - M - 2 * F)
            + 0.000549 * sin(4 * D + Mp)
            + 0.000537 * sin(4 * M)
            + 0.000520 * sin(4 * D - M)
            - 0.000487 * sin(D - 2 * Mp)
            - 0.000399 * sin(2 * D + M - 2 * F)
            - 0.000381 * sin(Mp - F)
            - 0.000371 * sin(D + M + Mp)
            + 0.000329 * sin(Mp + 2 * D - 2 * F)
            - 0.000317 * sin(2 * D + M - Mp - 2 * F)
            + 0.000306 * sin(D - M - Mp)
            - 0.000289 * sin(2 * M + Mp)
            - 0.000271 * sin(D - 2 * M)
            - 0.000264 * sin(D + 2 * Mp - 2 * F)
            - 0.000198 * sin(D - Mp + F)
            + 0.000173 * sin(3 * D - Mp - F)
            + 0.000168 * sin(D - M + Mp)
            + 0.000164 * sin(D + Mp - F)
            - 0.000120 * sin(D - M - Mp - F)
            - 0.000117 * sin(D + M + Mp + F)
            + 0.000115 * sin(4 * D + M - Mp)
            + 0.000107 * sin(2 * D - 2 * M + Mp))

        return lon % 360.0

    def get_current_mansion(self) -> dict:
        """منزل قمر فعلی + زمان ورود به منزل بعدی"""
        cache_key = f"moon_mansion_{datetime.now(timezone.utc).strftime('%Y%m%d%H')}"
        cached = nasa_cache.get(cache_key)
        if cached is not None:
            return cached

        now = datetime.now(timezone.utc)
        lon = self._moon_longitude(now)

        idx = int(lon // _MANSION_SPAN) % 28
        mansion = MOON_MANSIONS[idx]

        # درجه داخل منزل (0-12.86)
        deg_in = lon - (idx * _MANSION_SPAN)

        # زمان ورود ماه به منزل بعدی
        # سرعت متوسط ماه: ~13.176°/روز
        deg_to_next = _MANSION_SPAN - deg_in
        hours_to_next = deg_to_next / 13.176 * 24.0
        next_time = now.timestamp() + hours_to_next * 3600
        next_mansion = MOON_MANSIONS[(idx + 1) % 28]

        result = {
            "timestamp": int(now.timestamp()),
            "utc_date": now.strftime("%Y-%m-%d"),
            "moon_longitude": round(lon, 2),
            "mansion": {
                "num": mansion["num"],
                "name_fa": mansion["fa"],
                "name": mansion["name"],
                "stars": mansion["stars"],
                "meaning": mansion["meaning"],
                "interp": mansion["interp"],
                "mood": mansion["mood"],
            },
            "degree_in_mansion": round(deg_in, 1),
            "percent_of_mansion": round(deg_in / _MANSION_SPAN * 100, 1),
            "next": {
                "num": next_mansion["num"],
                "name_fa": next_mansion["fa"],
                "meaning": next_mansion["meaning"],
                "in_hours": round(hours_to_next, 1),
                "at_ts": int(next_time),
            },
        }
        nasa_cache.set(cache_key, result)
        return result


