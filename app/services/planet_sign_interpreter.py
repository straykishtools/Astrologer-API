def interpret_planet_sign(planet: str, sign: str) -> dict:
    """تفسیر فارسی یک ترکیبِ سیاره-برج"""
    pd = PLANET_DOMAIN.get(planet, {"fa": planet, "domain": "", "short": ""})
    ss = SIGN_STYLE.get(sign, {"fa": sign, "style": "", "key": ""})

    specific = PLANET_SIGN_SPECIFIC.get((planet, sign), "")
    if not specific:
        # قالبِ عمومی برای ترکیب‌های بدونِ متنِ اختصاصی
        specific = f"«{pd['short']}» تو با سبکِ «{ss['key']}» کار می‌کند: {ss['style']}."

    return {
        "planet_fa": pd["fa"],
        "planet_domain": pd["domain"],
        "sign_fa": ss["fa"],
        "sign_style": ss["style"],
        "interpretation": specific,
    }


def interpret_all(planets: dict) -> list:
    """تفسیر همه‌ی سیاراتِ پاس‌داده‌شده (dict از ssd_service)"""
    out = []
    for name, p in planets.items():
        t = interpret_planet_sign(name, p.get("sign", ""))
        out.append({
            "planet": name,
            "planet_fa": t["planet_fa"],
            "sign": p.get("sign", ""),
            "sign_fa": t["sign_fa"],
            "degree_in_sign": p.get("degree_in_sign", ""),
            "domain": t["planet_domain"],
            "interpretation": t["interpretation"],
        })
    return out
