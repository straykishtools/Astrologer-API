class NumerologyEngine:

    @staticmethod
    def _reduce_to_single(number: int) -> int:
        """کاهش عدد به یک رقم (۱ تا ۹) یا عدد اصلی (۱۱، ۲۲، ۳۳)"""
        if number in [11, 22, 33]:
            return number
        while number > 9:
            number = sum(int(d) for d in str(number))
        return number

    @staticmethod
    def _digit_sum(number: int) -> int:
        """جمع ارقام یک عدد"""
        return sum(int(d) for d in str(abs(number)))

    def _deep(self, n: int) -> dict:
        """تفسیر عمیق عدد (یا خالی برای اعداد ناشناخته)"""
        d = DEEP_NUMBERS.get(n)
        if not d:
            return {}
        return {
            "identity": d["identity"],
            "essence": d["essence"],
            "strengths": d["strengths"],
            "shadow": d["shadow"],
            "growth": d["growth"],
        }

    # ========== ۱. عدد مسیر زندگی (Life Path) ==========
