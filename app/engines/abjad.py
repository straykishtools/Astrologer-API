def _abjad_interp(total: int, method: str) -> dict:
    """تفسیر فارسی عدد ابجد"""
    if method != "kabir":
        return {}

    # عنصر بر اساس باقیمانده بر ۴
    element, element_desc = _ELEMENT_OF[total % 4]

    # عدد رقیق (تک‌رقمی)
    reduced = total
    while reduced > 9:
        reduced = sum(int(d) for d in str(reduced))

    # معنای مستقیم (اگر عدد شناخته‌شده است)
    direct = _ABJAD_MEANINGS.get(total, "")

    # اگر عدد مستقیم نیست، بر اساس رقم رقیق + عنصر تفسیر عمومی
    general = {
        1: "استقلال و آغاز — نامی که راهِ تازه باز می‌کند",
        2: "پیوند و همراهی — نامی که دل‌ها را نزدیک می‌کند",
        3: "بیان و خلاقیت — نامی که صدا و رنگ دارد",
        4: "ثبات و ساخت — نامی که پا می‌ماند",
        5: "حرکت و تجربه — نامی که سفر می‌رود",
        6: "عشق و مراقبت — نامی که خانه گرم می‌کند",
        7: "عمق و راز — نامی که فکر می‌کند",
        8: "قدرت و دستاورد — نامی که می‌سازد و می‌تراشد",
        9: "بخشش و کمال — نامی که می‌دهد و می‌آموزد",
    }.get(reduced, "")

    return {
        "element": element,
        "element_desc": element_desc,
        "reduced": reduced,
        "reduced_meaning": general,
        "direct_meaning": direct,
    }


def calculate_abjad(text: str, method: str = "kabir") -> dict:
    """
    محاسبه‌ی ابجد یک متن + تفسیر
    method: "kabir" یا "saghir"
    """
    if not text:
        return {"error": "متن وارد نشده است"}

    abjad_map = ABJAD_KABIR if method == "kabir" else ABJAD_SAGHIR

    total = 0
    details = []
    for char in text:
        value = abjad_map.get(char, 0)
        if value > 0:
            total += value
            details.append({"char": char, "value": value})

    return {
        "text": text,
        "method": method,
        "total": total,
        "details": details,
        "digit_sum": sum(int(d) for d in str(total)) if total > 0 else 0,
        "interp": _abjad_interp(total, method),
    }


def compare_names(name1: str, name2: str, method: str = "kabir") -> dict:
    """
    تطبیق دو نام بر اساس ابجد — با تفسیر فارسی
    """
    result1 = calculate_abjad(name1, method)
    result2 = calculate_abjad(name2, method)

    diff = abs(result1["total"] - result2["total"])

    # تشخیص سطح سازگاری + تفسیر
    if diff == 0:
        compatibility = "عالی"
        fa = "دو نام در یک وزن: آینه‌ی یکدیگر — هم‌راستا در مسیر و هدف"
    elif diff <= 10:
        compatibility = "عالی"
        fa = "نزدیکیِ وزن‌ها هم‌نوایی می‌سازد؛ دو نام هم‌قدم‌اند — گفت‌وگو روان و درکِ متقابل آسان"
    elif diff <= 30:
        compatibility = "خوب"
        fa = "تفاوتِ معقول: هر دو نقشِ خودش را دارد؛ مکمل‌اند اگر احترامِ تفاوت حفظ شود"
    elif diff <= 60:
        compatibility = "متوسط"
        fa = "دو وزنِ متفاوت: ریتمِ مشترک نیاز به ساختن دارد — گفت‌وگوی منظم، پُل می‌سازد"
    else:
        compatibility = "ضعیف"
        fa = "فاصله‌ی وزنیِ بزرگ: دو دنیایِ متفاوت — احترامِ صریح و توافق‌های شفاف لازم است"

    return {
        "name1": name1,
        "value1": result1["total"],
        "name2": name2,
        "value2": result2["total"],
        "difference": diff,
        "compatibility": compatibility,
        "fa": fa,
        "method": method
    }
